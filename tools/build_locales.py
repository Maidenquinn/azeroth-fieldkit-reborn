"""Compile reviewed JSON catalogs to Lua 5.0 data. No network or player data access."""
from pathlib import Path
import json,re
from lupa.lua51 import LuaRuntime

BASE = Path(__file__).resolve().parents[1]
LANGUAGES = ('pl', 'cs', 'de', 'pt', 'es', 'ro', 'tr', 'ru', 'uk', 'zh', 'ja', 'ko')

def quote(text):
    return json.dumps(text, ensure_ascii=False).replace('\\/', '/')

def build(check=False):
    glossary = json.loads((BASE / 'data/locale-glossary.json').read_text(encoding='utf8'))
    lua=LuaRuntime()
    for name in ('Localization.lua','InterfaceStrings.lua','International.lua'):
        lua.execute((BASE/'AzerothFieldKitReborn'/name).read_text(encoding='utf8'))
    required=set(lua.globals().FieldKitLocale.fr.keys())
    formats=re.compile(r'%%|%[-+0]*\d*(?:\.\d+)?[cdeEfgGiouXxsq]')
    outputs={}
    for code in LANGUAGES:
        catalog = json.loads((BASE / f'data/locales/{code}.json').read_text(encoding='utf8'))
        index = glossary['languages'].index(code)
        for key, values in glossary['terms'].items():
            catalog[key] = values[index]
        for key, original in glossary['aliases'].items():
            catalog[key] = catalog[original].upper() if key.isupper() else catalog[original]
        for key, prefix, word in [('01  HOME','01  ','Home'),('02  COMBAT','02  ','Combat'),
                                  ('03  INTERFACE','03  ','Interface'),('04  WORLD','04  ','World'),
                                  ('05  MULTIPLAYER','05  ','Multiplayer'),('06  CHAT','06  ','Chat'),
                                  ('07  PREFERENCES','07  ','Preferences')]:
            catalog[key] = prefix + catalog[word]
        missing=required-set(catalog)
        assert not missing, f'{code}: incomplete source catalog ({len(missing)} missing): {sorted(missing)[:8]}'
        for key,value in catalog.items():
            assert isinstance(value,str) and value.strip(),(code,'empty',key)
            assert formats.findall(key)==formats.findall(value),(code,'format placeholders',key,value)
            assert key.count('\n')==value.count('\n'),(code,'newlines',key)
        lines = ['-- Generated by tools/build_locales.py from data/locales; UTF-8, Lua 5.0.',
                 '-- Presentation strings only; never protocol identifiers or player names.',
                 f'local t={{}};FieldKitLocale.{code}=t']
        lines.extend(f't[{quote(key)}]={quote(value)}' for key, value in sorted(catalog.items()))
        raw = ('\n'.join(lines)+'\n').encode('utf8')
        path = BASE / f'AzerothFieldKitReborn/Locale_{code}.lua'
        outputs[path]=raw
    # Validate all languages before writing any runtime module.
    for path,raw in outputs.items():
        if check:assert path.read_bytes()==raw, f'Stale generated catalog: {path.name}'
        else:path.write_bytes(raw)
    print(f'PASS complete locale sources: {len(required)} canonical strings in 12 additional languages')

if __name__ == '__main__':
    import sys
    build('--check' in sys.argv)
