"""Read installed PE include_str! packs, emit only creature presentation metadata.

No executable code is run, no native client file is modified or redistributed.
The Rust pack table stores (path pointer, length, content pointer, length).
"""
import argparse
import hashlib
import json
import re
import struct
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def packs(exe):
    raw = exe.read_bytes()
    pe = struct.unpack_from('<I', raw, 60)[0]
    opt = pe + 24
    base = struct.unpack_from('<Q', raw, opt + 24)[0]
    start = opt + struct.unpack_from('<H', raw, pe + 20)[0]
    sections = [struct.unpack_from('<8sIIII', raw, start + 40*i)
                for i in range(struct.unpack_from('<H', raw, pe + 6)[0])]

    def address(offset):
        return next(base+rva+offset-ro for _, _, rva, size, ro in sections
                    if ro <= offset < ro+size)

    def offset(address):
        return next((ro+address-base-rva for _, _, rva, size, ro in sections
                     if base+rva <= address < base+rva+size), None)

    result = {}
    for match in re.finditer(rb'[a-zA-Z0-9_-]+/(?:[a-zA-Z0-9_-]+/)*[a-zA-Z0-9_-]+\.toml', raw):
        path = match.group().decode()
        if '/zones/' not in path and 'holiday' not in path and 'mode' not in path:
            continue
        ref = raw.find(struct.pack('<QQ', address(match.start()), len(match.group())))
        if ref < 0:
            continue
        pointer, length = struct.unpack_from('<QQ', raw, ref+16)
        at = offset(pointer)
        if at is None or not 0 < length < 500_000:
            continue
        try:
            result[path] = tomllib.loads(raw[at:at+length].decode('utf-8'))
        except (ValueError, UnicodeError):
            continue
    return result, hashlib.sha256(raw).hexdigest()


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--game', required=True, type=Path)
    parser.add_argument('--verify-icons', action='store_true', help='Check boss/seasonal BLP paths against readable MPQ hash tables (requires mpyq)')
    args = parser.parse_args()
    content, sha = packs(args.game/'AzerothSurvivorsGame.exe')
    zones = sorted((z for data in content.values() for z in data.get('zone', [])), key=lambda z: z['key'])
    assert len(zones) == 48, f'Expected 48 installed zones, found {len(zones)}'
    report = {'clientSha256': sha, 'source': 'installed include_str TOML packs', 'zones': [], 'seasonal': []}
    # These twelve final bosses have no icon in either their pack or AZS_GEN.
    # Explicit presentation choices; never presented as native icon metadata.
    boss_fallback = {700218: 'Achievement_Boss_Nefarion', 43391: 'Spell_Nature_EarthElemental_Totem',
                     700228: 'INV_Misc_Head_Dragon_Black', 700198: 'Achievement_Boss_Ragnaros',
                     700118: 'Ability_TheBlackArrow', 700208: 'Spell_Shadow_Shadowfiend',
                     700188: 'Spell_Fire_LavaSpawn', 700148: 'Spell_Fire_Elemental_Totem',
                     700128: 'Achievement_Boss_Magtheridon', 700168: 'Achievement_Reputation_Ogre',
                     700138: 'Spell_Nature_Lightning', 700158: 'Achievement_Boss_LadyVashj'}
    lines = ['-- Generated by tools/build_reborn_creatures.py; names/icons only, installed Reborn packs.',
             'FieldKitRebornCreatures={zones={']
    for zone in zones:
        creatures = [(kind, c) for kind in ('enemy', 'elite', 'boss') for c in zone.get(kind, [])]
        assert all(c.get('entry') and c['name']['en'] for _, c in creatures)
        native_icons = {c['entry']: c.get('icon') for _, c in creatures}
        for kind, creature in creatures:
            if not creature.get('icon'):
                creature['icon'] = boss_fallback.get(creature['entry'], zone['icon'])
        lines.append(' ['+quote(zone['key'])+']={')
        for kind, creature in creatures:
            lines.append('  {name='+quote(creature['name']['en'])+',icon='+quote(creature['icon'])+
                         ',entry='+str(creature['entry'])+',kind='+quote(kind)+'},')
        lines.append(' },')
        report['zones'].append({'key': zone['key'], 'bosses': [{'name': c['name']['en'], 'entry': c['entry'], 'icon': c['icon'], 'status': 'native' if native_icons[c['entry']] else 'presentation fallback; no native icon'} for c in zone.get('boss', [])],
                                'creatures': len(creatures)})
    lines.append('},seasonal={')
    # Holiday looks have display ids, but no icon field or creatureIcons entry.
    # These are explicit, labelled presentation fallbacks, never fabricated entries.
    fallback = {21822: 'INV_Helmet_96', 158: 'Spell_Shadow_AnimateDead', 915: 'Spell_Shadow_Possession', 146: 'Spell_Holy_GuardianSpirit'}
    for path, data in content.items():
        for holiday in data.get('holiday', []):
            for creature in holiday.get('looks', []):
                icon = fallback.get(creature.get('display_id'))
                if not icon:
                    continue
                lines.append(' {name='+quote(creature['name']['en'])+',icon='+quote(icon)+'},')
                report['seasonal'].append({'name': creature['name']['en'], 'display': creature['display_id'], 'icon': icon, 'source': path, 'status': 'presentation fallback; no native icon'})
    lines.append('}}')
    if args.verify_icons:
        import mpyq
        hashes, archives = set(), []
        for path in sorted((args.game/'Data').rglob('*')):
            if path.suffix.lower() != '.mpq':
                continue
            with path.open('rb') as stream:
                if stream.read(4) != b'MPQ\x1a':
                    continue  # Encrypted AZSR containers are not opened.
            archive = mpyq.MPQArchive(str(path), listfile=False)
            hashes.update((e.hash_a, e.hash_b) for e in archive.hash_table if e.block_table_index < 0xfffffffe)
            archive.file.close()
            archives.append(path.name)
        icons = {b['icon'] for z in report['zones'] for b in z['bosses']} | {c['icon'] for c in report['seasonal']}
        missing = []
        for icon in sorted(icons):
            path = 'Interface\\Icons\\'+icon+'.blp'
            if (archive._hash(path, 'HASH_A'), archive._hash(path, 'HASH_B')) not in hashes:
                missing.append(icon)
        assert not missing, f'Unverified boss/seasonal icon paths: {missing}'
        report['bossIconAssets'] = {'verifiedPaths': len(icons), 'archives': archives, 'missing': missing,
                                   'method': 'read-only MPQ hash tables; encrypted AZSR containers not opened'}
    (ROOT/'AzerothFieldKitReborn/RebornCreatures.lua').write_text('\n'.join(lines)+'\n', encoding='utf-8', newline='\n')
    (ROOT/'docs/REBORN_CREATURE_COVERAGE.json').write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n', encoding='utf-8', newline='\n')
    print(f'{len(zones)} zones, {sum(len(z["bosses"]) for z in report["zones"])} bosses, {sum(z["creatures"] for z in report["zones"])} creatures, {len(report["seasonal"])} seasonal fallbacks')


if __name__ == '__main__':
    main()
